import json
import re
from typing import TypedDict

from evals.llm import LLMClient


JUDGE_PROMPT = """You are an evaluator of customer support answers for an online store.

Task: score the assistant's answer to the customer's question.

Criteria:
- It is correct according to the return policy (30 days, unused product).
- It is polite and clear.
- It does not make up information that is not in the policy.

Scale:
1 = incorrect or makes up information
3 = correct but confusing or incomplete
5 = correct, clear and complete

Example of a score of 1:
Question: "Can I return some sneakers I bought 2 months ago?"
Answer: "Of course! You can return them whenever you want."
Reason: it contradicts the 30-day policy.

Question: {question}
Answer: {answer}

Reply ONLY with JSON: {{"score": <1-5>, "reason": "<one sentence>"}}"""


class Verdict(TypedDict):
    score: int
    reason: str


def parse_verdict(text: str) -> Verdict:
    """
        Extract the JSON verdict from the judge's answer.
        Models sometimes add text around the JSON, so we look for the first {...} block.
        Params:
            - text: Raw text returned by the judge
        Returns:
            A dict with the score and the reason
    """

    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError(f"The judge did not return JSON: {text!r}")

    data = json.loads(match.group())
    return {"score": int(data["score"]), "reason": str(data["reason"])}


def judge(question: str, answer: str, llm: LLMClient) -> Verdict:
    """
        Use an LLM as a judge to score an answer without a reference answer.
        Remember: a judge is the model AND the prompt. Change either one
        and the scores are no longer comparable with previous ones.
        Params:
            - question: Question asked by the user
            - answer: Answer generated by the chatbot
            - llm: LLM client used as the judge (e.g. ChatGPTClient)
        Returns:
            The judge's verdict (score and reason)
    """

    prompt = JUDGE_PROMPT.format(question=question, answer=answer)
    return parse_verdict(llm.ask(prompt))
