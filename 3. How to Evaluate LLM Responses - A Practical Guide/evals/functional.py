from typing import Callable


# Pretend this function was written by an LLM after the prompt:
# "Write a function that returns the letter of a Spanish ID number (DNI)"
GENERATED_CODE = '''
def id_letter(number):
    letters = "TRWAGMYFPDXBNJZSQVHLCKE"
    return letters[number % 23]
'''

# Test cases we already know the answer to: (DNI number, expected letter)
TEST_CASES = [
    (12345678, "Z"),
    (0, "T"),
    (87654321, "X"),
]


def load_function(code: str, function_name: str) -> Callable:
    """
        Execute code generated by an LLM and return one of its functions.
        In a real system, run untrusted code inside a sandbox.
        Params:
            - code: Source code returned by the model
            - function_name: Name of the function to extract
        Returns:
            The function object
    """

    namespace = {}
    exec(code, namespace)
    return namespace[function_name]


def functional_correctness(code: str) -> bool:
    """
        Evaluate generated code by running it against known test cases.
        Params:
            - code: Source code returned by the model
        Returns:
            True if every test case passes, False otherwise
    """

    try:
        id_letter = load_function(code, "id_letter")
        return all(id_letter(number) == letter for number, letter in TEST_CASES)
    except Exception:
        # Code that does not compile or crashes is simply wrong
        return False


def pass_at_k(samples: list[str]) -> bool:
    """
        pass@k: the problem counts as solved if ANY of the k samples passes.
        Params:
            - samples: k different code samples generated for the same prompt
        Returns:
            True if at least one sample passes all the tests
    """

    return any(functional_correctness(code) for code in samples)
